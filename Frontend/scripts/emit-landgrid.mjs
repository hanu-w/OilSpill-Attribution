import { createJiti } from 'jiti';
const jiti = createJiti(import.meta.url, { fsCache: false });
const fs = await import('node:fs');
const turf = await jiti.import('../node_modules/@turf/turf/dist/esm/index.js');
const data = JSON.parse(fs.readFileSync('/tmp/ne_50m_land.geojson','utf8'));

const LNG0 = 65.5, LAT0 = 18.5, STEP = 0.02;
const COLS = Math.round((73.5 - LNG0)/STEP), ROWS = Math.round((25.5 - LAT0)/STEP);
const bytesPerRow = Math.ceil(COLS/8);
const ERODE = 2;

const polys = [];
for (const f of data.features) {
  const g = f.geometry;
  if (g.type==='Polygon') polys.push({type:'Polygon', coordinates:g.coordinates});
  else if (g.type==='MultiPolygon') for (const c of g.coordinates) polys.push({type:'Polygon', coordinates:c});
}
const regionPolys = polys.filter(p=>{const b=turf.bbox(p);return b[0]<73.5&&b[2]>65.5&&b[1]<25.5&&b[3]>18.5;});

const land = new Uint8Array(ROWS*bytesPerRow);
for(let r=0;r<ROWS;r++){
  const lat = LAT0 + r*STEP;
  for(let c=0;c<COLS;c++){
    const lng = LNG0 + c*STEP;
    if(regionPolys.some(p=>turf.booleanPointInPolygon([lng,lat],p))) land[r*bytesPerRow+(c>>3)] |= (1<<(c%8));
  }
}
function get(buf,r,c){ return (buf[r*bytesPerRow+(c>>3)] & (1<<(c%8)))!==0; }
const safe = new Uint8Array(ROWS*bytesPerRow);
for(let r=0;r<ROWS;r++){
  for(let c=0;c<COLS;c++){
    let ok=true;
    outer:
    for(let dr=-ERODE;dr<=ERODE;dr++){
      for(let dc=-ERODE;dc<=ERODE;dc++){
        const rr=r+dr, cc=c+dc;
        if(rr<0||rr>=ROWS||cc<0||cc>=COLS){ ok=false; break outer; }
        if(get(land,rr,cc)){ ok=false; break outer; }
      }
    }
    if(ok) safe[r*bytesPerRow+(c>>3)] |= (1<<(c%8));
  }
}
function b64(u8){ return Buffer.from(u8).toString('base64'); }

